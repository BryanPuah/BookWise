/**
 * schema.js — canonical data model for Bookwise.
 *
 * Entities live in the store (`src/store.js`) as plain objects in arrays. This
 * file is the single source of truth for their *shapes* — JSDoc typedefs that
 * IDEs can read, enum constants the rest of the app should pull from instead
 * of hard-coding strings, and factory functions so every creation site emits
 * a fully-populated object.
 *
 * Nothing here changes runtime behavior. The store and existing call sites
 * keep working unchanged. New code should prefer the factories so we stop
 * accumulating one-off shapes.
 *
 * Persistence: there is none yet — state is in-memory `useState`. When that
 * lands, this file is where the schema version + migration hooks belong.
 *
 * ── Field conventions ─────────────────────────────────────────────────────
 *   - `id`         opaque string, generated by `genId(prefix)`
 *   - `createdAt`  ISO-8601 string (new field — older entities may lack it)
 *   - `updatedAt`  ISO-8601 string (new field — older entities may lack it)
 *   - `date`       'YYYY-MM-DD' — calendar date in the user's local zone
 *
 * ── Known legacy / derived fields (kept for backcompat) ───────────────────
 *   Note.type     — singular, duplicates `types[0]`. Older list views read it.
 *   Note.isQuote  — derived from `types[0] === 'quote'`. Written at save time
 *                   but not re-derived on edit. Don't trust for new code; read
 *                   `types` instead.
 *   Note.text     — flattened plain-text view of `blocks`. Regenerated on save
 *                   via `blocksToText()`. Acts as the search index.
 *   Book.dateAdded — documented in CLAUDE.md but historically never set. The
 *                   `newBook()` factory below now populates it.
 *   Goal.recurrence undefined — legacy goals are treated as 'daily' (see
 *                   `goalsForDate` in store.js).
 */

// ─── ID generation ─────────────────────────────────────────────────────────
// Single canonical ID generator. Prefix narrows the namespace so a quick
// glance at an id tells you what kind of thing it points to.
export function genId(prefix = '') {
  const t = Date.now();
  const r = Math.random().toString(36).slice(2, 8);
  return prefix ? `${prefix}_${t}_${r}` : `${t}_${r}`;
}

