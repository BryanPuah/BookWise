// ─── Factories ─────────────────────────────────────────────────────────────
// Every creation site should prefer these so new fields land everywhere at
// once. Pass a `patch` to override defaults — extra keys are spread through
// unchanged so callers can carry custom payloads (Open Library metadata etc.).

const nowIso = () => new Date().toISOString();
// Local-zone YYYY-MM-DD. Must match store.js — see the comment there.
const todayKey = () => {
  const d = new Date();
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
};
const pickCover = () => COVER_KEYS[Math.floor(Math.random() * COVER_KEYS.length)];

/**
 * Build a fully-formed Book. Required: title. Everything else defaults.
 * @param {Partial<Book> & { title: string }} patch
 * @returns {Book}
 */
export function newBook(patch) {
  if (!patch || !patch.title) throw new Error('newBook: title is required');
  return {
    id:          genId('bk'),
    olKey:       null,
    title:       patch.title,
    author:      '',
    cover:       pickCover(),
    coverId:     null,
    pageCount:   0,
    currentPage: 0,
    genres:      [],
    description: '',
    status:      BOOK_STATUS.WANT,
    rating:      0,
    format:      BOOK_FORMAT.BOOK,
    url:         '',
    dateAdded:   nowIso(),
    finishedAt:  null,
    ...patch,
  };
}

/**
 * Build a fully-formed Note. Required: at least one of `blocks` or `text`.
 *
 * The factory keeps the legacy fields populated (type, isQuote, text) so
 * older readers keep working. Callers should pass `blocks` and `types`; the
 * derived fields are filled in for them.
 *
 * @param {Partial<Note> & { blocks?: Block[], types?: NoteType[] }} patch
 * @param {(blocks: Block[]) => string} [flatten]  Optional `blocksToText` impl —
 *   pass it in to avoid circular imports from the editor module.
 * @returns {Note}
 */
export function newNote(patch = {}, flatten) {
  const blocks = patch.blocks || [];
  const types  = patch.types && patch.types.length ? patch.types : [NOTE_TYPE.INSIGHT];
  const primary = types[0];
  const text = patch.text != null
    ? patch.text
    : (flatten ? flatten(blocks) : '');

  return {
    id:            genId('n'),
    bookId:        '',
    bookTitle:     '',
    title:         '',
    blocks,
    types,
    type:          primary,                       // legacy mirror
    text,                                         // derived
    thinking:      '',
    page:          '',
    chapter:       '',
    tags:          [],
    linkedNoteIds: types.includes(NOTE_TYPE.CONNECTION) ? (patch.linkedNoteIds || []) : [],
    isQuote:       primary === NOTE_TYPE.QUOTE,   // legacy mirror
    starred:       false,
    date:          todayKey(),
    ...patch,
    // Re-apply derived fields after spread so callers can't accidentally
    // desync `type` / `isQuote` from `types`.
    type:    primary,
    isQuote: primary === NOTE_TYPE.QUOTE,
  };
}

/**
 * Build a fully-formed Goal. Validates the recurrence-specific field.
 * @param {Partial<Goal> & { label: string, recurrence: GoalRecurrence }} patch
 * @returns {Goal}
 */
export function newGoal(patch) {
  if (!patch || !patch.label) throw new Error('newGoal: label is required');
  if (!patch.recurrence)      throw new Error('newGoal: recurrence is required');

  switch (patch.recurrence) {
    case GOAL_RECURRENCE.WEEKLY:
      if (typeof patch.weekday !== 'number') throw new Error('newGoal: weekly recurrence needs weekday (0-6)');
      break;
    case GOAL_RECURRENCE.MONTHLY:
      if (typeof patch.monthDay !== 'number') throw new Error('newGoal: monthly recurrence needs monthDay (1-31)');
      break;
    case GOAL_RECURRENCE.ONCE:
      if (!patch.dueDate) throw new Error('newGoal: once recurrence needs dueDate (YYYY-MM-DD)');
      break;
  }

  return {
    id:         genId('g'),
    label:      patch.label,
    tag:        '',
    recurrence: patch.recurrence,
    created:    todayKey(),
    ...patch,
  };
}

/**
 * Build a GoalCompletion. (goalId, date) is the natural key.
 * @param {string} goalId
 * @param {string} date  'YYYY-MM-DD'
 * @returns {GoalCompletion}
 */
export function newGoalCompletion(goalId, date) {
  return { goalId, date, completedAt: nowIso() };
}

/**
 * Build a Reflection.
 * @param {string} date  'YYYY-MM-DD'
 * @param {string} text
 * @returns {Reflection}
 */
export function newReflection(date, text) {
  return { id: genId('r'), date, text, updatedAt: nowIso() };
}

/**
 * Build a fresh User. Empty `name` means logged out — App.js routes to LoginScreen.
 * @param {Partial<User>} [patch]
 * @returns {User}
 */
export function newUser(patch = {}) {
  return { name: '', email: '', avatarSeed: '', ...patch };
}

// ─── Tag normalization ─────────────────────────────────────────────────────
// Tags are stored uppercase, trimmed, no whitespace runs. Search call sites
// should run inputs through this too so comparison stays case-insensitive.
export function normalizeTag(input) {
  return String(input || '')
    .trim()
    .replace(/\s+/g, ' ')
    .toUpperCase();
}
